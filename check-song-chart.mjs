import assert from 'node:assert/strict';
import {createSongChart,gridBeats,songSettings,waveformPeaks} from './dist/song-chart.mjs';
const close=(a,b)=>assert.ok(Math.abs(a-b)<.00001,`${a} ≠ ${b}`);
const config={bpm:120,offset:.25,segments:[{time:4.25,bpm:180},{time:7.25,bpm:90}]};
const beats=gridBeats(10,config);
assert.deepEqual(beats.slice(0,4),[.25,.75,1.25,1.75]);
assert.deepEqual(beats.filter(t=>t>=4.25&&t<5.25),[4.25,4.58333,4.91667]);
assert.equal(beats.filter(t=>t===7.25).length,1);close(beats.at(-1),9.91667);
assert.ok(beats.every((t,i)=>!i||t>beats[i-1]));
const analysis={beatMap:{offset:1.2,beats:[1.2,1.7,2.2,2.6,3],confidence:.9},events:[{time:1.2,strength:1,kind:'bass'},{time:1.45,strength:.9,kind:'high'},{time:1.5,strength:.4},{time:1.85,strength:.1}]};
const chart=createSongChart({duration:5,bpm:120,offset:1.2,analysis});
assert.equal(chart.automatic,true);assert.deepEqual(chart.beats,analysis.beatMap.beats);
assert.ok(chart.events.some(e=>e.time===1.45&&!e.beat),'Contretemps fort jouable');
assert.ok(!chart.events.some(e=>e.time===1.85),'Petit bruit filtré');
assert.ok(chart.events.every((e,i)=>!i||e.time-chart.events[i-1].time>=.18));
const unsure=createSongChart({duration:5,bpm:120,offset:1.2,analysis:{...analysis,beatMap:{...analysis.beatMap,confidence:.1}}});
assert.ok(unsure.events.every(e=>analysis.events.some(o=>Math.abs(o.time-e.time)<.075)),'Aucun coup interpolé sans attaque quand la confiance est basse');
const silent=createSongChart({duration:5,bpm:120,offset:1.2,analysis:{beatMap:analysis.beatMap,events:[],waveform:new Array(64).fill(0)}});
assert.equal(silent.events.length,0,'Le silence conserve le clock sans imposer des frappes');
assert.equal(chart.rhythm.judge(1.455).grade,'perfect');
assert.equal(chart.rhythm.judge(1.545).grade,'good');
assert.ok(chart.rhythm.upcoming(1.1,2).length>3,'Plusieurs notes anticipées');
assert.equal(chart.rhythm.event(9999),null,'Pas de boucle inventée après le fichier');
const shifted=createSongChart({duration:5,bpm:120,offset:1.3,analysis});close(shifted.beats[0],1.3);close(shifted.events[1].time,1.55);
const manual=createSongChart({duration:10,analysis,chart:{source:'grid',...config}});
assert.equal(manual.automatic,false);assert.deepEqual(manual.beats,beats);assert.equal(manual.events.length,beats.length);
const clean=songSettings({duration:20,chart:{bpm:999,offset:-4,segments:[{time:4,bpm:120},{time:4,bpm:180},{time:3,bpm:NaN},{time:500,bpm:100}]}});
assert.equal(clean.bpm,240);assert.equal(clean.offset,0);assert.deepEqual(clean.segments,[{time:4,bpm:120}]);
assert.deepEqual(waveformPeaks(new Float32Array(100),10),new Array(10).fill(0));
assert.deepEqual(waveformPeaks(Float32Array.from([0,-.5,1,0]),2),[.5,1]);
const serialized=JSON.parse(JSON.stringify({config,analysis}));assert.deepEqual(serialized.config,config);
console.log('Cartes musicales : sections 120→180→90 BPM, contretemps, offset, fenêtres, aperçu, fin et forme d’onde validés.');
